#!/usr/bin/env bash
# DomainPilot installer bootstrap (Phase 2a: host baseline).
#
#   sudo installer/install.sh [--vars FILE] [--check] [--yes] [-- EXTRA-ANSIBLE-ARGS]
#
#   --vars FILE   host settings (default /etc/domainpilot/install.yml; generated
#                 on first run from the invoking admin's SSH keys)
#   --check       dry run: show what would change (ansible --check --diff)
#   --yes         don't ask for confirmation
#
# Run it via sudo from the admin account you SSH in with. That account becomes
# the first DomainPilot admin, so hardening cannot lock you out.
set -euo pipefail
umask 027
export PATH=/usr/sbin:/usr/bin:/sbin:/bin LC_ALL=C.UTF-8

die() { echo "install.sh: ERROR: $*" >&2; exit 1; }
info() { echo "install.sh: $*"; }

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VARS=/etc/domainpilot/install.yml
CHECK=()
ASSUME_YES=0
EXTRA=()

while [[ $# -gt 0 ]]; do
  case "$1" in
    --vars) VARS="${2:?--vars needs a file}"; shift 2 ;;
    --check) CHECK=(--check --diff); shift ;;
    --yes) ASSUME_YES=1; shift ;;
    --) shift; EXTRA=("$@"); break ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) die "unknown option: $1 (see --help)" ;;
  esac
done

[[ $EUID -eq 0 ]] || die "run with sudo"
# shellcheck source=/dev/null
. /etc/os-release
case "${ID:-}:${VERSION_ID:-}" in ubuntu:24.04|ubuntu:26.04) ;; *) die "Ubuntu 24.04 or 26.04 LTS required (found ${PRETTY_NAME:-unknown})" ;; esac

confirm() {
  [[ $ASSUME_YES -eq 1 ]] && return 0
  [[ -t 0 ]] || die "not a terminal; re-run with --yes to proceed non-interactively"
  local reply; read -r -p "$1 [y/N] " reply
  [[ $reply =~ ^[Yy]$ ]]
}

yaml_quote() { local s=${1//\'/\'\'}; printf "'%s'" "$s"; }

# The client IP of the SSH session that started us. sudo clears SSH_CONNECTION,
# so read it from the nearest ancestor process that still has it.
operator_ip() {
  local pid=$$ conn="" ip
  while [[ $pid =~ ^[0-9]+$ ]] && (( pid > 1 )); do
    conn="$(tr '\0' '\n' <"/proc/$pid/environ" 2>/dev/null | sed -n 's/^SSH_CONNECTION=//p' | head -1)"
    [[ -n $conn ]] && break
    pid="$(ps -o ppid= -p "$pid" 2>/dev/null | tr -d ' ')"
  done
  ip="${conn%% *}"
  [[ -n $ip ]] || return 0
  python3 -I -c 'import ipaddress, sys; ipaddress.ip_address(sys.argv[1])' "$ip" 2>/dev/null \
    && printf '%s' "$ip"
  return 0
}

generate_vars() {
  local user="${SUDO_USER:-}"
  [[ -n $user && $user != root ]] || die "no $VARS found and not run via sudo from an admin account; create $VARS (see ansible/group_vars/all.yml)"
  [[ $user =~ ^[a-z][a-z0-9_-]{0,30}$ ]] || die "account name '$user' is not a valid DomainPilot admin name"
  local home keyfile
  home="$(getent passwd "$user" | cut -d: -f6)"
  if [[ -s /etc/ssh/authorized_keys.d/$user ]]; then keyfile=/etc/ssh/authorized_keys.d/$user
  else keyfile="$home/.ssh/authorized_keys"; fi
  [[ -f $keyfile && ! -L $keyfile ]] || die "no authorized_keys for $user ($keyfile); add your SSH key first"

  local keys=()
  while IFS= read -r line; do
    keys+=("$line")
  done < <(grep -E '^(ssh-ed25519|sk-ssh-ed25519@openssh\.com|ecdsa-sha2-nistp(256|384|521)|sk-ecdsa-sha2-nistp256@openssh\.com|ssh-rsa) [A-Za-z0-9+/]+={0,3}( .*)?$' "$keyfile" || true)
  [[ ${#keys[@]} -gt 0 ]] || die "no usable keys in $keyfile (keys with options like from= are not imported)"

  local admin_ip
  admin_ip="$(operator_ip)"

  info "First run: '$user' becomes the first DomainPilot admin with ${#keys[@]} key(s) from $keyfile."
  info "After hardening: SSH is key-only, root login is disabled, and only dp-admins can log in."
  if [[ -n $admin_ip ]]; then
    info "Your SSH source address $admin_ip will never be banned by fail2ban (dp_fail2ban_ignoreip)."
  else
    info "Could not detect your SSH source address; consider setting dp_fail2ban_ignoreip."
  fi
  confirm "Continue?" || die "aborted"

  install -d -m 0750 "$(dirname "$VARS")"
  {
    echo "---"
    echo "# Generated by installer/install.sh on $(date -Is). Review and edit freely."
    echo "dp_admins:"
    echo "  - name: $user"
    echo "    ssh_keys:"
    for k in "${keys[@]}"; do echo "      - $(yaml_quote "$k")"; done
    if [[ -n $admin_ip ]]; then
      echo "# Address the installer was run from. Remove it if it is dynamic or shared."
      echo "dp_fail2ban_ignoreip:"
      echo "  - $(yaml_quote "$admin_ip")"
    fi
  } >"$VARS.tmp"
  chmod 0640 "$VARS.tmp"
  mv -f "$VARS.tmp" "$VARS"
  info "Wrote $VARS"
}

[[ -f $VARS ]] || generate_vars

if ! command -v ansible-playbook >/dev/null 2>&1; then
  info "Installing ansible-core from the Ubuntu archive"
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq ansible-core \
    || die "could not install ansible-core (is the 'universe' component enabled?)"
fi

export ANSIBLE_CONFIG="$REPO/ansible/ansible.cfg"
info "Running playbook ${CHECK[*]:+(${CHECK[*]})}"
ansible-playbook -i localhost, -c local "$REPO/ansible/site.yml" \
  -e "@$VARS" "${CHECK[@]}" "${EXTRA[@]}"

if [[ -e /var/lib/domainpilot/firewall/pending ]]; then
  cat <<'EOF'

  ************************************************************************
  *  FIREWALL CHANGE PENDING: it rolls back automatically unless you     *
  *  confirm it. Keep this session open, open a NEW ssh session, and run: *
  *                                                                      *
  *      sudo dp-firewall confirm                                        *
  *                                                                      *
  *  If the new session cannot connect, do nothing: it reverts itself.   *
  ************************************************************************
EOF
fi
info "Done."
