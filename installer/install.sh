#!/usr/bin/env bash
# ozenix installer: fresh installs and upgrades (docs/install.md, docs/upgrade.md).
#
#   sudo installer/install.sh [--vars FILE] [--check] [--yes] [--allow-downgrade] [-- EXTRA-ANSIBLE-ARGS]
#
#   --vars FILE   host settings (default /etc/ozenix/install.yml; created
#                 on the first run)
#   --check       dry run: show what would change (ansible --check --diff)
#   --yes         don't ask for confirmation
#   --allow-downgrade  install an older release (see docs/runbooks/rollback.md)
#
# Run it as root (or with sudo). Your own SSH/root login is left as it is;
# every site gets its own Linux user when it is created.
set -euo pipefail
umask 027
export PATH=/usr/sbin:/usr/bin:/sbin:/bin LC_ALL=C.UTF-8

die() { echo "install.sh: ERROR: $*" >&2; exit 1; }
info() { echo "install.sh: $*"; }

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VARS=/etc/ozenix/install.yml
CHECK=()
DOWNGRADE=()
ASSUME_YES=0
EXTRA=()

while [[ $# -gt 0 ]]; do
  case "$1" in
    --vars) VARS="${2:?--vars needs a file}"; shift 2 ;;
    --check) CHECK=(--check --diff); shift ;;
    --yes) ASSUME_YES=1; shift ;;
    --allow-downgrade) DOWNGRADE=(--allow-downgrade); shift ;;
    --) shift; EXTRA=("$@"); break ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    *) die "unknown option: $1 (see --help)" ;;
  esac
done

[[ $EUID -eq 0 ]] || die "run with sudo"
# shellcheck source=/dev/null
. /etc/os-release
case "${ID:-}:${VERSION_ID:-}" in ubuntu:24.04|ubuntu:26.04) ;; *) die "Ubuntu 24.04 or 26.04 LTS required (found ${PRETTY_NAME:-unknown})" ;; esac

confirm() {
  [[ $ASSUME_YES -eq 1 ]] && return 0
  [[ -t 0 ]] || die "not a terminal; re-run with --yes to proceed non-interactively"
  local reply; read -r -p "$1 [y/N] " reply
  [[ $reply =~ ^[Yy]$ ]]
}

yaml_quote() { local s=${1//\'/\'\'}; printf "'%s'" "$s"; }

# The client IP of the SSH session that started us. sudo clears SSH_CONNECTION,
# so read it from the nearest ancestor process that still has it.
operator_ip() {
  local pid=$$ conn="" ip
  while [[ $pid =~ ^[0-9]+$ ]] && (( pid > 1 )); do
    conn="$(tr '\0' '\n' <"/proc/$pid/environ" 2>/dev/null | sed -n 's/^SSH_CONNECTION=//p' | head -1)"
    [[ -n $conn ]] && break
    pid="$(ps -o ppid= -p "$pid" 2>/dev/null | tr -d ' ')"
  done
  ip="${conn%% *}"
  [[ -n $ip ]] || return 0
  python3 -I -c 'import ipaddress, sys; ipaddress.ip_address(sys.argv[1])' "$ip" 2>/dev/null \
    && printf '%s' "$ip"
  return 0
}

generate_vars() {
  local admin_ip
  admin_ip="$(operator_ip)"
  info "First run: installing the ozenix web server stack."
  info "Your current SSH/root login is not changed. Each site gets its own user (site <domain> create --user NAME --key FILE)."
  if [[ -n $admin_ip ]]; then
    info "Your address $admin_ip will never be banned by fail2ban (dp_fail2ban_ignoreip)."
  fi
  confirm "Continue?" || die "aborted"

  install -d -m 0750 "$(dirname "$VARS")"
  {
    echo "---"
    echo "# Generated by installer/install.sh on $(date -Is). Review and edit freely;"
    echo "# every setting is documented in ansible/group_vars/all.yml."
    if [[ -n $admin_ip ]]; then
      echo "# Address the installer was run from. Remove it if it is dynamic or shared."
      echo "dp_fail2ban_ignoreip:"
      echo "  - $(yaml_quote "$admin_ip")"
    else
      echo "{}"
    fi
  } >"$VARS.tmp"
  chmod 0640 "$VARS.tmp"
  mv -f "$VARS.tmp" "$VARS"
  info "Wrote $VARS"
}

# Servers installed under the previous name: move their files first (one-time).
# shellcheck source=installer/upgrade-rename.sh
. "$REPO/installer/upgrade-rename.sh"
if [[ ${#CHECK[@]} -eq 0 ]]; then
  rename_move
elif [[ -d /etc/$RENAME_OLD && ! -e /etc/$RENAME_NEW ]]; then
  die "this server still uses the previous name: run without --check once to upgrade it"
fi

[[ -f $VARS ]] || generate_vars

# --- Release identity and upgrade policy (docs/upgrade.md) -------------------
STATE_DIR=/var/lib/ozenix
RELEASE_JSON=$STATE_DIR/release.json
SNAP_DIR=/var/backups/ozenix

release_py() {
  python3 -IB -c 'import sys; sys.path.insert(0, sys.argv[1]); from ozenix.release import installer_main; raise SystemExit(installer_main(sys.argv[2:]))' "$REPO" "$@"
}

# A release tarball carries MANIFEST.sha256 (covered by the signed SHA256SUMS):
# refuse to run from a tree whose files differ from what was released.
if [[ -f $REPO/MANIFEST.sha256 ]]; then
  (cd "$REPO" && sha256sum --quiet --strict -c MANIFEST.sha256) \
    || die "release files do not match MANIFEST.sha256: re-download and verify the release"
fi

if [[ -f $REPO/RELEASE ]]; then
  COMMIT="$(sed -n 's/^commit=\([0-9a-f]\{7,40\}\)$/\1/p' "$REPO/RELEASE")"
else
  COMMIT="$(git -c "safe.directory=$REPO" -C "$REPO" rev-parse --short=12 HEAD 2>/dev/null || true)"
fi
[[ $COMMIT =~ ^[0-9a-f]{7,40}$ ]] || COMMIT=unknown

PLAN="$(release_py plan "$RELEASE_JSON" "${DOWNGRADE[@]}")" || exit 3
read -r ACTION FROM_VERSION TO_VERSION <<<"$PLAN"
case "$ACTION" in
  fresh) info "Installing ozenix $TO_VERSION" ;;
  reinstall) info "Re-applying ozenix $TO_VERSION" ;;
  upgrade|downgrade)
    info "${ACTION^}: ozenix $FROM_VERSION -> $TO_VERSION (read docs/upgrade.md first)"
    [[ ${#CHECK[@]} -gt 0 ]] || confirm "Continue?" || die "aborted"
    ;;
  *) die "unexpected upgrade plan: $PLAN" ;;
esac

# Everything needed to roll back ozenix's own state: registry (copied
# consistently with SQLite's online backup), settings, secrets, generated
# configs. Root-only; the newest 5 are kept.
snapshot_state() {
  local ts tmp out
  ts="$(date +%Y%m%dT%H%M%S)"
  out="$SNAP_DIR/pre-upgrade-$FROM_VERSION-to-$TO_VERSION-$ts.tar.gz"
  install -d -m 0700 "$SNAP_DIR"
  tmp="$(mktemp -d "$SNAP_DIR/.snap.XXXXXX")"
  if [[ -f $STATE_DIR/registry.sqlite3 ]]; then
    python3 -I -c 'import sqlite3, sys
src = sqlite3.connect("file:" + sys.argv[1] + "?mode=ro", uri=True)
dst = sqlite3.connect(sys.argv[2])
src.backup(dst)
dst.close()
src.close()' "$STATE_DIR/registry.sqlite3" "$tmp/registry.sqlite3"
  fi
  local paths=()
  for p in etc/ozenix var/lib/ozenix etc/nginx etc/php etc/mysql \
           etc/apparmor.d/ozenix etc/ssh/sshd_config.d etc/nftables.conf; do
    [[ -e /$p ]] && paths+=("$p")
  done
  tar --create --gzip --file "$out" \
      --exclude=var/lib/ozenix/backup/cache \
      --exclude='var/lib/ozenix/registry.sqlite3*' \
      -C / "${paths[@]}" -C "$tmp" . \
    || { rm -rf "$tmp" "$out"; die "pre-upgrade snapshot failed; nothing was changed"; }
  chmod 0600 "$out"
  rm -rf "$tmp"
  info "Pre-upgrade snapshot: $out"
  find "$SNAP_DIR" -maxdepth 1 -name 'pre-upgrade-*.tar.gz' -type f -printf '%T@ %p\n' \
    | sort -rn | tail -n +6 | cut -d' ' -f2- | xargs -r rm -f --
}

if [[ ${#CHECK[@]} -eq 0 && ( $ACTION == upgrade || $ACTION == downgrade ) ]]; then
  snapshot_state
fi

if ! command -v ansible-playbook >/dev/null 2>&1; then
  info "Installing ansible-core from the Ubuntu archive"
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq ansible-core \
    || die "could not install ansible-core (is the 'universe' component enabled?)"
fi

export ANSIBLE_CONFIG="$REPO/ansible/ansible.cfg"
info "Running playbook ${CHECK[*]:+(${CHECK[*]})}"
ansible-playbook -i localhost, -c local "$REPO/ansible/site.yml" \
  -e "@$VARS" "${RENAME_EXTRA[@]}" "${CHECK[@]}" "${EXTRA[@]}"


if [[ ${#CHECK[@]} -eq 0 ]]; then
  rename_cleanup
fi

if [[ ${#CHECK[@]} -eq 0 ]]; then
  release_py record "$RELEASE_JSON" "$STATE_DIR/release-history.jsonl" "$COMMIT" \
    || die "installed, but could not record the release in $RELEASE_JSON"
  info "ozenix $TO_VERSION ($COMMIT) is installed."
fi

# ozenix leaves the server's own login as you configured it; say so loudly if
# that means passwords are accepted (site users are always keys-only).
if /usr/sbin/sshd -T 2>/dev/null | grep -qE '^(passwordauthentication yes|permitrootlogin yes)$'; then
  cat <<'EOF'

  NOTICE: this server's SSH accepts passwords (for root or other accounts).
  ozenix does not change your own login. Keys only is strongly recommended:
      echo -e 'PasswordAuthentication no\nPermitRootLogin prohibit-password' \
        | sudo tee /etc/ssh/sshd_config.d/01-keys-only.conf && sudo systemctl reload ssh
  (Test a key login from a second session first.) Site users are always keys-only.
EOF
fi

if [[ -e /var/lib/ozenix/firewall/pending ]]; then
  cat <<'EOF'

  ************************************************************************
  *  FIREWALL CHANGE PENDING: it rolls back automatically unless you     *
  *  confirm it. Keep this session open, open a NEW ssh session, and run: *
  *                                                                      *
  *      sudo dp-firewall confirm                                        *
  *                                                                      *
  *  If the new session cannot connect, do nothing: it reverts itself.   *
  ************************************************************************
EOF
fi
info "Done."
